"""TTF -> LovyanGFX/TFT_eSPI smooth font (VLW) as a C header.

Usage: uv run --with freetype-py tools/make_vlw.py
Writes cricket_scoreboard/fonts_smooth.h with every font in FONTS below.
VLW layout (big-endian int32): header[6] = count, version, size, 0, ascent, descent;
then per glyph [7] = code, height, width, xAdvance, topExtent, leftExtent, 0;
then each glyph's 8-bit alpha bitmap (width*height bytes).
"""
import struct
from pathlib import Path
import freetype

ROOT = Path(__file__).resolve().parent.parent
FONTDIR = ROOT / "tools" / "fonts"
OUT = ROOT / "cricket_scoreboard" / "fonts_smooth.h"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
DIGITS = " 0123456789/-.%"

# name, ttf, pixel size, charset
FONTS = [
    ("F_LABEL", "Geist-SemiBold.ttf", 11, ASCII),   # uppercase labels
    ("F_BODY",  "Geist-Medium.ttf", 13, ASCII),     # secondary text
    ("F_NAME",  "Geist-SemiBold.ttf", 15, ASCII),   # names, team codes
    ("F_NUM_S", "GeistMono-Medium.ttf", 13, ASCII),
    ("F_NUM_M", "GeistMono-SemiBold.ttf", 17, ASCII),
    ("F_NUM_L", "GeistMono-SemiBold.ttf", 24, DIGITS),
    ("F_SCORE", "Geist-SemiBold.ttf", 42, DIGITS),  # the big score
]


def build(ttf: str, px: int, chars: str) -> bytes:
    face = freetype.Face(str(FONTDIR / ttf))
    face.set_pixel_sizes(0, px)
    glyphs, bitmaps = [], []
    for ch in sorted(set(chars), key=ord):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        buf = bytearray()
        for r in range(h):
            row = bm.buffer[r * bm.pitch: r * bm.pitch + w]
            buf.extend(row)
        adv = int(round(g.advance.x / 64))
        glyphs.append((ord(ch), h, w, adv, g.bitmap_top, g.bitmap_left))
        bitmaps.append(bytes(buf))

    def top_of(c):
        face.load_char(c, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        return face.glyph.bitmap_top, face.glyph.bitmap.rows

    asc = top_of("d" if "d" in chars else "0")[0]
    t, rows = top_of("p" if "p" in chars else "0")
    desc = max(0, rows - t)
    out = bytearray(struct.pack(">6i", len(glyphs), 11, px, 0, asc, desc))
    for code, h, w, adv, top, left in glyphs:
        out += struct.pack(">7i", code, h, w, adv, top, left, 0)
    for b in bitmaps:
        out += b
    return bytes(out)


def main():
    lines = ["#pragma once", "// Generated by tools/make_vlw.py from Geist (SIL OFL 1.1). Do not edit.",
             "#include <stdint.h>", "#include <pgmspace.h>", ""]
    total = 0
    for name, ttf, px, chars in FONTS:
        data = build(ttf, px, chars)
        total += len(data)
        lines.append(f"// {ttf} {px}px, {len(data)} bytes")
        lines.append(f"const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};\n")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({total} bytes of font data)")


if __name__ == "__main__":
    main()
